import http from "node:http";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import { resolve, sep } from "node:path";
import { performance } from "node:perf_hooks";

const contentTypes = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".ico": "image/x-icon",
};

export function createApp({
  environment = "local",
  commit = "local",
  version = "1.0.0",
  drills = false,
  allowedOrigins = [],
  staticDir = resolve("dist"),
  log = (entry) => process.stdout.write(JSON.stringify(entry) + "\n"),
} = {}) {
  const started = performance.now();
  const state = {
    ready: true,
    shuttingDown: false,
    requests: 0,
    errors: 0,
    samples: [],
    events: [],
  };
  const event = (type, message) => {
    const item = {
      id: randomUUID(),
      at: new Date().toISOString(),
      type,
      message,
    };
    state.events.unshift(item);
    state.events.splice(12);
    log({ level: "info", event: type, message, timestamp: item.at });
  };
  const json = (response, code, data) => {
    response.writeHead(code, {
      "Content-Type": "application/json; charset=utf-8",
      "Cache-Control": "no-store",
    });
    response.end(JSON.stringify(data));
  };
  const server = http.createServer(async (request, response) => {
    const start = performance.now();
    const requestId = randomUUID();
    response.setHeader("X-Request-Id", requestId);
    response.setHeader("X-Content-Type-Options", "nosniff");
    response.setHeader("Referrer-Policy", "no-referrer");
    response.setHeader(
      "Content-Security-Policy",
      "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self'; frame-ancestors 'self'; base-uri 'self'; object-src 'none'",
    );
    let path = "/invalid-url";
    try {
      path = decodeURIComponent(
        new URL(request.url, "http://localhost").pathname,
      );
    } catch {
      json(response, 400, { error: "Invalid URL" });
      return;
    }
    response.on("finish", () => {
      const durationMs = Math.round((performance.now() - start) * 100) / 100;
      // Count traffic generated by the test button; polling and probes are excluded.
      if (path === "/api/probe") {
        state.requests++;
        if (response.statusCode >= 500) state.errors++;
        state.samples.push(durationMs);
        if (state.samples.length > 100) state.samples.shift();
      }
      log({
        level: response.statusCode >= 500 ? "error" : "info",
        event: "http_request",
        method: request.method,
        path,
        status: response.statusCode,
        durationMs,
        requestId,
        timestamp: new Date().toISOString(),
      });
    });
    try {
      if (request.method === "GET" && path === "/health/live")
        return json(response, 200, { status: "alive" });
      if (request.method === "GET" && path === "/health/ready")
        return json(response, state.ready && !state.shuttingDown ? 200 : 503, {
          status: state.ready && !state.shuttingDown ? "ready" : "not_ready",
        });
      if (request.method === "GET" && path === "/api/status")
        return json(response, 200, {
          name: "LearnOps",
          version,
          commit,
          environment,
          uptimeSeconds: Math.floor((performance.now() - started) / 1000),
          ready: state.ready && !state.shuttingDown,
          drillsEnabled: drills,
          nodeVersion: process.version,
        });
      if (request.method === "GET" && path === "/api/metrics") {
        const sorted = [...state.samples].sort((a, b) => a - b);
        return json(response, 200, {
          probeRequests: state.requests,
          probeErrors: state.errors,
          errorRatePercent: state.requests
            ? Math.round((state.errors / state.requests) * 1000) / 10
            : 0,
          p95LatencyMs: sorted.length
            ? sorted[Math.ceil(sorted.length * 0.95) - 1]
            : null,
          sampleWindow: sorted.length,
          events: state.events,
        });
      }
      if (request.method === "POST" && path === "/api/probe") {
        if (!state.ready || state.shuttingDown)
          return json(response, 503, {
            error: "Readiness drill is active",
            requestId,
          });
        return json(response, 200, {
          message: "Request served successfully",
          requestId,
        });
      }
      if (request.method === "POST" && path === "/api/drills/readiness") {
        if (!drills)
          return json(response, 403, {
            error: "Drills are disabled in this environment",
          });
        const origin = request.headers.origin;
        if (
          origin &&
          new URL(origin).host !== request.headers.host &&
          !allowedOrigins.includes(origin)
        )
          return json(response, 403, {
            error: "Cross-origin drills are not allowed",
          });
        let body = "";
        for await (const chunk of request) {
          body += chunk;
          if (body.length > 1024)
            return json(response, 413, { error: "Request body too large" });
        }
        let data;
        try {
          data = JSON.parse(body);
        } catch {
          return json(response, 400, { error: "Expected a JSON body" });
        }
        if (typeof data.degraded !== "boolean")
          return json(response, 400, { error: "degraded must be a boolean" });
        state.ready = !data.degraded;
        event(
          data.degraded ? "drill_started" : "service_recovered",
          data.degraded
            ? "Readiness disabled for a local incident exercise."
            : "Readiness restored. New requests can succeed.",
        );
        return json(response, 200, { ready: state.ready });
      }
      if (path.startsWith("/api/") || path.startsWith("/health/"))
        return json(response, 404, { error: "Endpoint not found" });
      if (!["GET", "HEAD"].includes(request.method))
        return json(response, 405, { error: "Method not allowed" });
      const file = resolve(
        staticDir,
        "." + (path === "/" ? "/index.html" : path),
      );
      if (!file.startsWith(resolve(staticDir) + sep))
        return json(response, 403, { error: "Invalid path" });
      const extension = file.slice(file.lastIndexOf("."));
      let bytes;
      try {
        bytes = await readFile(file);
      } catch {
        return json(response, 404, {
          error: "File not found. Run npm run build before npm start.",
        });
      }
      response.writeHead(200, {
        "Content-Type": contentTypes[extension] ?? "application/octet-stream",
        "Cache-Control": path.startsWith("/assets/")
          ? "public, max-age=31536000, immutable"
          : "no-cache",
      });
      response.end(request.method === "HEAD" ? undefined : bytes);
    } catch (error) {
      log({
        level: "error",
        event: "request_failed",
        requestId,
        message: error.message,
      });
      if (!response.headersSent)
        json(response, 500, { error: "Internal server error", requestId });
      else response.end();
    }
  });
  server.requestTimeout = 10_000;
  server.headersTimeout = 15_000;
  event(
    "service_started",
    "Service process started. Metrics describe this process only.",
  );
  return {
    server,
    state,
    markShuttingDown() {
      state.shuttingDown = true;
      event("shutdown_started", "Readiness disabled; draining requests.");
    },
  };
}
